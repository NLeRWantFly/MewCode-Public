"""Register command-produced files through the same verified file hook."""
from pydantic import BaseModel, Field
from mewcode.tools.base import Tool, ToolResult, resolve_tool_path


class ReportArtifactParams(BaseModel):
    file_path: str = Field(description="Exact path of an existing process/output file")


class ReportArtifact(Tool):
    name = "ReportArtifact"
    description = ("Register an existing file generated by a command for the node's process-file panel. "
                   "Use after generating reports, images or other files. This does not mark it accepted.")
    params_model = ReportArtifactParams
    category = "read"
    is_concurrency_safe = True

    async def execute(self, params):
        path = resolve_tool_path(params.file_path)
        try:
            exists = path.is_file()
        except OSError:
            exists = False
        return ToolResult(output="File verified for registration" if exists else "File does not exist",
                          is_error=not exists)
