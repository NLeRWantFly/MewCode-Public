"""Converge a private structural repair draft before offering adoption."""
from __future__ import annotations

import copy
import json
import time

from .graph_build_control import CONTROL_GUIDANCE, SoftBuildControl, model_object
from .graph_local_repair import SCHEMA, SYSTEM, _locked, preview_repair


def preview_upserts(preview):
    """Recover a host-checked local draft, never import a wider chat edit."""
    edits = []
    for change in preview.get("changes", []):
        before, after = change.get("before"), change["after"]
        if after.get("state") == "retired":
            continue  # Host provenance cleanup is regenerated by validation.
        edit = {"id": change["entry_id"], "rationale": change["reason"]}
        for key in ("kind", "title", "body"):
            if before is None or before.get(key) != after.get(key):
                edit[key] = copy.deepcopy(after[key])
        edit["data"] = {k: copy.deepcopy(v) for k, v in after.get("data", {}).items()
                        if before is None or before.get("data", {}).get(k) != v}
        if edit.get("data") or len(edit) > 3:
            edits.append(edit)
    return edits


async def build_repair(snapshot, base, packet, *, ask_model, checkpoint, report,
                       guard, resume=None, seed=None):
    """All cumulative edits are checked against the original protected graph."""
    work = copy.deepcopy(resume or {})
    work.setdefault("prompt", packet["prompt"])
    work.setdefault("upserts", preview_upserts(seed) if seed else [])
    work.setdefault("rounds", [])
    work.setdefault("summary", "完善当前图的执行结构。")
    policy = SoftBuildControl(work.get("control"))
    payload = json.loads(work["prompt"])
    payload["ticket"] = packet["ticket"]
    locked = {e["id"]: _locked(e) and e["id"] not in (snapshot.get("repair_request") or {}).get("saved_structural_ids", [])
              for e in snapshot["candidate"]["document"]["entries"]}
    trial = None
    feedback = seed.get("validation", {}) if seed else {}

    async def save(control=None):
        if control is not None:
            work["control"] = control
        else:
            work["control"] = copy.deepcopy(policy.state)
        await checkpoint(copy.deepcopy(work))

    async def call(system, user):
        started = time.monotonic()
        raw = await ask_model(system, user)
        policy.add_request(raw, time.monotonic() - started)
        return raw

    if work["upserts"]:
        trial = preview_repair(snapshot, base, {"schema": SCHEMA, "ticket": packet["ticket"],
            "summary": work["summary"], "upserts": work["upserts"]}, max_changes=None)
        feedback = trial["validation"]
    await save()
    while True:
        guard()
        if trial and trial["validation"]["valid"]:
            trial["repair_status"] = "ready"
            trial["summary"] = f"已完成 {len(trial['changes'])} 项结构修订，并通过整图执行结构校验。" + work["summary"]
            trial["round_count"] = len(work["rounds"])
            trial["entry_labels"] = {e["id"]: e.get("title", e["id"]) for e in trial["document"]["entries"]}
            return trial
        if trial:
            payload["entries"] = [{**{k: e[k] for k in ("id", "kind", "title", "body", "data", "state")},
                "locked": locked.get(e["id"], False)} for e in trial["document"]["entries"] if e["state"] != "retired"]
        payload["diagnostics"] = feedback.get("diagnostics", payload.get("diagnostics", []))
        payload["previous_feedback"] = work["rounds"][-2:]
        payload["continuation"] = policy.state["decisions"][-1:]
        report({"stage": "preparing", "detail": "AI 正在完善修订，通过校验后才展示可采用的改动。",
                "request_round": len(work["rounds"]) + 1,
                "focus_entry_ids": list({i for d in payload["diagnostics"] for i in d.get("entry_ids", [])})})
        raw = await call(SYSTEM + CONTROL_GUIDANCE, json.dumps(payload, ensure_ascii=False))
        guard()
        report({"stage": "validating", "detail": "正在核对修订后的完整执行结构。"})
        record = {"round": len(work["rounds"]) + 1, "status": "refining"}
        before = copy.deepcopy(work["upserts"])
        proposal = None
        try:
            proposal = model_object(raw)
            if not isinstance(proposal, dict) or proposal.get("ticket") != packet["ticket"]:
                raise ValueError("修订单版本不匹配")
            edits = proposal.get("upserts")
            if not isinstance(edits, list) or len(edits) > 32 or any(not isinstance(e, dict) for e in edits):
                raise ValueError("结构变更必须为至多32项的对象数组")
            merged = {e["id"]: copy.deepcopy(e) for e in work["upserts"]}
            for edit in edits:
                key = edit.get("id")
                if not isinstance(key, str):
                    raise ValueError("变更缺少条目标识")
                old = merged.get(key, {})
                merged[key] = {**old, **edit, "data": {**old.get("data", {}), **edit.get("data", {})}}
            proposal = {**proposal, "upserts": list(merged.values())}
            trial_next = preview_repair(snapshot, base, proposal, max_changes=None)
            trial = trial_next
            work["upserts"] = proposal["upserts"]
            work["summary"] = proposal["summary"]
            feedback = trial["validation"]
            record.update(status="ready" if feedback["valid"] else "refining",
                          changes=len(trial["changes"]), diagnostics=copy.deepcopy(feedback["diagnostics"]))
        except (ValueError, TypeError, KeyError) as exc:
            record.update(status="rejected", diagnostics=[{"code": "proposal_rejected", "message": str(exc)[:1800]}])
            feedback = {"valid": False, "diagnostics": record["diagnostics"]}
        work["rounds"].append(record)
        await save()
        if trial and trial["validation"]["valid"]:
            continue
        material = lambda edits: [{k: v for k, v in e.items() if k != "rationale"} for e in edits]
        await policy.assess(raw, ask_model=call, stalled=material(before) == material(work["upserts"]),
            feedback={"phase": "structural_repair", "validation": feedback,
                      "last_attempt": record}, checkpoint=save)
