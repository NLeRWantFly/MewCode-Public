const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'../frontend/static');
const context=vm.createContext({URL,console});context.window=context;
for(const file of ['vendor/marked.min.js','file-links.js','markdown-render.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const local=context.MewFileLinks.localPath;
for(const value of ['C:/资料/结果.json','/C:/资料/结果.json','file:///C:/%E8%B5%84%E6%96%99/%E7%BB%93%E6%9E%9C.json','C:\\资料\\结果.json'])assert.equal(local(value),'C:/资料/结果.json');
assert.equal(local('/C:/资料/结果.json:12'),'C:/资料/结果.json');
assert.equal(local('docs/说明.md',true),'docs/说明.md');
for(const value of ['https://example.com/a.md','mailto:a@example.com','#section','/api/workbench/artifact?id=a','javascript:alert(1)','file://server/share','//server/share'])assert.equal(local(value),null,value);
const html=context.MewMarkdown.renderMarkdown('[目录](/C:/资料) [文件](<C:/资料/结果 文件.json>) [相对](docs/说明.md) [网页](https://example.com/page)');
assert.match(html,/data-file-reference="C:\/资料"/);
assert.match(html,/data-file-reference="C:\/资料\/结果 文件.json"/);
assert.match(html,/data-file-reference="docs\/说明.md"/);
assert.match(html,/href="https:\/\/example.com\/page"/);
assert.doesNotMatch(html,/href="\/?C:/);
console.log('file_links: Windows paths, encoded paths, relative citations and web URLs passed');
