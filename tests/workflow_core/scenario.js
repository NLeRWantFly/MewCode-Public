(async()=>{
      const assert=(v,s)=>{if(!v)throw Error(s);};
      const wait=async(f,label)=>{for(let i=0;i<150;i++){if(await f())return;await new Promise(r=>setTimeout(r,200));}throw Error('Timeout: '+label);};
      const get=async()=> (await fetch('/workflow-acceptance-state')).json();
      const click=(text,root=document)=>{const b=[...root.querySelectorAll('button')].find(b=>b.textContent.trim()===text&&!b.disabled);assert(b,'button '+text);b.click();};
      const field=(label,value)=>{const el=document.querySelector('[aria-label="'+label+'"]');assert(el,'field '+label);el.value=value;el.dispatchEvent(new Event('change',{bubbles:true}));};
      await wait(()=>document.querySelectorAll('.wb-workflow-card').length===6,'canvas');
      click('对话');click('适应');
      document.querySelector('.wb-run-button').click();
      await wait(async()=> (await get()).started.length===2,'parallel OCR');
      click('任务');
      assert((await get()).state.nodes.independent.status==='completed','unrelated branch continues');
      document.querySelector('.wb-workflow-card[data-node-id="database"]').click();
      click('前插判断');
      await wait(()=>document.querySelectorAll('.wb-workflow-card').length===7,'insert draft');
      const check=[...document.querySelectorAll('.wb-workflow-card')].find(c=>c.dataset.nodeId.startsWith('check_'));
      const checkId=check.dataset.nodeId;check.click();click('编辑');
      field('名称','核对两份识别结果');field('任务／判断条件','确认识别结果 A 已生成');
      field('判断方式','expression');field('条件字段','inputs.ocr_a.text');field('等于（JSON 值）','"PAGE A"');click('保存');
      await wait(async()=> (await get()).state.draft?.nodes.find(n=>n.id===checkId)?.config.expression?.path==='inputs.ocr_a.text','save');
      click('应用并继续');
      await wait(async()=>!(await get()).state.pending_apply,'apply');
      await fetch('/workflow-acceptance-release',{method:'POST'});
      await wait(async()=> (await get()).state.status==='completed','OCR to database');
      await wait(()=>document.querySelector('.wb-workflow-card[data-node-id="database"]').dataset.status==='已完成','completed view');
      const first=await get();assert(first.calls.filter(v=>v==='environment').length===1,'environment retained');
      assert(first.calls.filter(v=>v==='independent').length===1,'independent retained');
      assert(first.state.nodes[checkId].result.value===true,'inserted judgment executes');
      const ocr=document.querySelector('.wb-workflow-card[data-node-id="ocr_a"]');
      assert(ocr.querySelectorAll('.wb-workflow-progress li').length===5,'five public updates');
      assert(ocr.querySelector('footer a').href.includes('/api/workbench/artifact'),'clickable artifact');
      ocr.click();await wait(()=>document.querySelectorAll('.wb-workflow-message').length>=8,'full public transcript');
      assert(!document.querySelector('.wb-workflow-conversation').textContent.includes('Diagnostic detail'),'diagnostics separate');
      assert(!document.querySelector('.wb-workflow-diagnostics').open,'diagnostics collapsed');
      click('预览',document.querySelector('.wb-workflow-artifacts'));
      await wait(()=>document.querySelector('.wb-workflow-file-preview')?.textContent==='PAGE A','artifact preview');
      click('仅重跑此节点');
      await wait(async()=> (await get()).calls.filter(v=>v==='ocr_a').length===2,'single node rerun');
      await wait(async()=> (await get()).state.status==='paused','held successors');
      assert((await get()).calls.filter(v=>v==='database').length===1,'no automatic successor');
      document.querySelector('.wb-workflow-card[data-node-id="'+checkId+'"]').click();
      click('从此处继续');await wait(async()=> (await get()).state.status==='completed','local continuation');
      const final=await get();assert(final.calls.filter(v=>v==='database').length===2,'database rerun');
      assert(final.calls.filter(v=>v==='environment').length===1,'earlier work preserved');
      window.MewWorkbench.store.refresh();await wait(()=>document.querySelector('.wb-workflow-card[data-node-id="database"]').dataset.status==='已完成','refresh');
      click('×',document.querySelector('.wb-node-inspector'));click('适应');
      return {ocr:true,runningEdit:true,parallel:true,localRerun:true,publicProgress:true,artifactPreview:true,graphRevision:final.state.graph.revision,attempts:Object.keys(final.state.attempts).length};
    })()
